#!/usr/bin/env bash
# ~/homelab/photos-local.sh: local care of the Immich library (RUNBOOK.md step 7c).
# Nightly by homelab-photos-local.timer (04:00, before the Proton copy at 04:30): all of it.
# `photos-local.sh copy`: step 2 only, without dedupe (homelab-photos-copy.service: hourly and
# after every change, backup-watch.sh). Or by hand.
#
# 1. Dedupe: two accounts can hold the same photos (a shared library imported into both);
#    Immich only dedupes per account. duperemove makes identical files share their blocks
#    (XFS reflink); the kernel compares the bytes first, and a later change to one copy gets
#    its own blocks again. Immich sees nothing.
# 2. Second copy on the primary SSD (Kingston, btrfs) in $COPY/current: the originals, the same
#    folders as the Proton copy (thumbs/ and encoded-video/ are regenerated by Immich). Files
#    deleted or replaced in Immich move to $COPY/deleted/<date>/ and are kept 30 days.
#    Then the copy is deduped too (btrfs supports the same).
set -euo pipefail
cd "$(dirname "$0")"
SRC=$(sed -n 's/^IMMICH_UPLOAD_DIR=//p' .env | tail -n1)
COPY=${PHOTOS_COPY_DIR:-/srv/photos-copy}
KEEP_DELETED_DAYS=30
CACHE=${CACHE_DIRECTORY:-$HOME/.cache/homelab}; mkdir -p "$CACHE"
MODE=${1:-all}
[[ $MODE == all || $MODE == copy ]] || { echo "usage: photos-local.sh [copy]" >&2; exit 2; }
# One at a time: the nightly run and the hourly copy write to the same place
mkdir -p "$HOME/.local/state/homelab"; exec 9>"$HOME/.local/state/homelab/photos-local.lock"
flock -w 3600 9 || { echo "another photos-local.sh is still running" >&2; exit 1; }

# Never mirror an empty mountpoint: rsync --delete would empty the copy
mountpoint -q "$SRC" && [[ -f "$SRC/library/.immich" ]] || { echo "$SRC not mounted or not Immich's" >&2; exit 1; }
[[ -d "$COPY" && -w "$COPY" ]] || { echo "$COPY missing or not writable (immich-wizard.sh stage 9)" >&2; exit 1; }

dedupe() {  # dedupe NAME DIR: hashes are kept, so only new or changed files are read again
  duperemove -r -d -q --hashfile="$CACHE/duperemove-$1.hash" "$2" >/dev/null
}

if [[ $MODE == all ]]; then
  echo "Dedupe $SRC/library…"
  dedupe photos "$SRC/library"
fi

# Second guard: if the library suddenly has far fewer files than the copy, something is wrong
# (a broken mount, a bad Immich migration). Stop rather than move the copy to deleted/.
if [[ -d "$COPY/current/library" ]]; then
  have=$(find "$SRC/library" -type f | wc -l); had=$(find "$COPY/current/library" -type f | wc -l)
  (( have * 2 >= had )) || { echo "library has $have files, the copy $had: not mirroring" >&2; exit 1; }
fi

echo "Copy → $COPY/current…"
dirs=()
for d in library upload profile backups; do [[ -d "$SRC/$d" ]] && dirs+=("$SRC/$d"); done
mkdir -p "$COPY/current"
rc=0
rsync -a --delete --backup --backup-dir="$COPY/deleted/$(date +%F)" "${dirs[@]}" "$COPY/current/" || rc=$?
# 24 = files vanished while copying: upload/ churns while the phones sync, that's fine
(( rc == 0 || rc == 24 )) || { echo "rsync failed ($rc)" >&2; exit "$rc"; }
find "$COPY/deleted" -mindepth 1 -maxdepth 1 -type d -mtime +"$KEEP_DELETED_DAYS" -exec rm -rf {} + 2>/dev/null || true

if [[ $MODE == all ]]; then
  echo "Dedupe $COPY/current…"
  dedupe copy "$COPY/current"
fi
echo "Done: $(du -sh "$COPY" | cut -f1) on the primary SSD."
